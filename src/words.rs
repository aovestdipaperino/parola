/// Pick a word of the given length from the list.
#[allow(dead_code)]
pub fn word_of_length(len: usize) -> Option<&'static str> {
    WORDS.iter().copied().find(|w| w.len() == len)
}

/// Pick a random word whose length is within `[min_len, max_len]`.
pub fn random_word(min_len: usize, max_len: usize) -> Option<&'static str> {
    let mut rng = rand::rng();
    let candidates: Vec<&str> = WORDS
        .iter()
        .copied()
        .filter(|w| (min_len..=max_len).contains(&w.len()))
        .collect();
    if candidates.is_empty() {
        return None;
    }
    let idx = rng.random_range(0..candidates.len());
    Some(candidates[idx])
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_length_has_words() {
        for len in 3..=14 {
            assert!(
                word_of_length(len).is_some(),
                "no word of length {len} in the list"
            );
        }
    }

    #[test]
    fn word_of_length_matches_exact_length() {
        for len in 3..=14 {
            if let Some(w) = word_of_length(len) {
                assert_eq!(w.len(), len, "word {w} has wrong length");
            }
        }
    }

    #[test]
    fn random_word_respects_bounds() {
        for _ in 0..50 {
            let w = random_word(3, 8).unwrap();
            assert!(
                (3..=8).contains(&w.len()),
                "word {w} has length {}",
                w.len()
            );
        }
    }
}
